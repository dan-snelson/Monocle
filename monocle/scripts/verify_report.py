class Git:
    def __init__(self, repo):
        self.repo = str(repo)

    def run(self, *args, data=None):
        # Arguments are a fixed git subcommand plus refs and hashes this script validated; no shell.
        return subprocess.run(["git", "-C", self.repo, *args], input=data,
                              capture_output=True, env=GIT_ENV, check=False)

    def out(self, *args, data=None):
        proc = self.run(*args, data=data)
        if proc.returncode:
            raise VerifyError(f"git {args[0]} failed: {proc.stderr.decode(errors='replace').strip()}")
        return proc.stdout

    def ok(self, *args):
        return self.run(*args).returncode == 0

    def resolve(self, rev):
        proc = self.run("rev-parse", "--verify", "--quiet", rev + "^{commit}")
        return proc.stdout.decode().strip() if proc.returncode == 0 else None

    def tree(self, commit):
        proc = self.run("rev-parse", "--verify", "--quiet", commit + ":monocle")
        return proc.stdout.decode().strip() if proc.returncode == 0 else None

    def refs(self):
        remote = [f"refs/remotes/origin/{b}" for b in CANONICAL_BRANCHES if self.resolve(f"refs/remotes/origin/{b}")]
        local = [f"refs/heads/{b}" for b in CANONICAL_BRANCHES if self.resolve(f"refs/heads/{b}")]
        tags = self.out("for-each-ref", "--format=%(refname)", "refs/tags").decode().split()
        return (remote or local) + tags

    def manifest(self, commit):
        listing = self.out("ls-tree", "-r", "-z", "--full-tree", commit, "--", "monocle")
        pending = []
        for record in listing.split(b"\0"):
            if not record:
                continue
            meta, path = record.split(b"\t", 1)
            mode, kind, oid = meta.decode().split()
            parts = path.decode("utf-8").split("/")
            if kind != "blob" or mode == "120000" or parts[-1] in MANIFEST_SKIP_FILES or MANIFEST_SKIP_DIRS & set(parts):
                continue
            pending.append(("./" + "/".join(parts[1:]), oid))
        batch = self.out("cat-file", "--batch", data="".join(f"{oid}\n" for _, oid in pending).encode())
        entries, position = [], 0
        for relative, _ in pending:
            newline = batch.index(b"\n", position)
            size = int(batch[position:newline].split()[2])
            content = batch[newline + 1:newline + 1 + size]
            entries.append((relative, hashlib.sha256(content).hexdigest()))
            position = newline + 1 + size + 1
        return manifest_digest(entries)

    def find_manifest(self, digest, refs):
        commits = self.out("rev-list", f"--max-count={MAX_HISTORY}", *refs, "--", "monocle").decode().split()
        seen = {}
        for commit in commits:
            tree = self.tree(commit)
            if tree not in seen:
                seen[tree] = self.manifest(commit)
            if seen[tree] == digest:
                return commit
        return None


def open_canonical(args):
    """Return (git, description, temp dir or None, whether the source is the canonical repository)."""
    if args.canonical:
        path = Path(args.canonical).resolve()
        git = Git(path)
        if not git.ok("rev-parse", "--git-dir"):
            raise VerifyError(f"{path} is not a git repository")
        origin = git.run("remote", "get-url", "origin").stdout.decode().strip()
        return git, f"local clone {path} (origin {origin or 'none'})", None, normalize_url(origin) == CANONICAL_URL
    temp = tempfile.mkdtemp(prefix="monocle-verify-")
    proc = subprocess.run(["git", "clone", "--quiet", "--no-checkout", CANONICAL_URL + ".git", temp],
                          capture_output=True, env=GIT_ENV, check=False)
    if proc.returncode:
        shutil.rmtree(temp, ignore_errors=True)
        raise VerifyError(f"could not fetch {CANONICAL_URL}: {proc.stderr.decode(errors='replace').strip()}")
    return Git(temp), f"fetched {CANONICAL_URL}", temp, True


def check_provenance(audit, git, refs):
    """Check the attestation against the canonical repository; return the commit whose rules apply."""
    att = audit.attestation
    if not att:
        audit.note("provenance", "attestation", "skip", "no attestation to check against the canonical repository")
        return None
    claimed, digest, dirty = att.get("skill_commit", ""), att.get("skill_sha256", ""), att.get("skill_dirty", "")
    short_refs = ", ".join(ref.split("/")[-1] for ref in refs)
    if COMMIT_RE.match(claimed):
        full = git.resolve(claimed)
        if not full:
            audit.add("provenance", "commit known", False, f"skill_commit {claimed} doesn't exist in the canonical repository")
            return None
        reachable = any(git.ok("merge-base", "--is-ancestor", full, ref) for ref in refs)
        audit.add("provenance", "commit reachable", reachable,
                  f"{full[:12]} {'is' if reachable else 'is not'} on a canonical ref ({short_refs})")
        tree = git.tree(full)
        audit.add("provenance", "tree hash", att.get("skill_tree") == tree,
                  f"attested skill_tree {att.get('skill_tree')}; canonical {full[:12]}:monocle is {tree}")
        canonical_digest = git.manifest(full)
        audit.add("provenance", "content hash", digest == canonical_digest,
                  f"attested skill_sha256 {digest[:16]}…; canonical manifest at {full[:12]} is {canonical_digest[:16]}…")
        audit.add("provenance", "clean tree", dirty == "false",
                  f"skill_dirty: {dirty}; a skill with local edits (for example, an un-upstreamed post-chat-refine) isn't canonical")
        check_context_version(audit, git, full)
        return full
    match = git.find_manifest(digest, refs) if SHA256_RE.match(digest) else None
    audit.add("provenance", "content hash", match is not None,
              f"copied install matches canonical commit {match[:12]}" if match
              else f"skill_sha256 {digest[:16]}… matches no monocle/ tree on {short_refs}")
    check_context_version(audit, git, match)
    return match


def check_context_version(audit, git, commit):
    """A v1 block from a skill commit that already has deployment-context.md hides the context field."""
    if not commit or audit.attestation.get("monocle_attestation") != "v1":
        return
    has_context = git.ok("cat-file", "-e", f"{commit}:{CONTEXT_REFERENCE}")
    audit.add("provenance", "attestation version", not has_context,
              f"v1 attestation, but {commit[:12]} has {CONTEXT_REFERENCE} and writes v2 with deployment_context"
              if has_context else f"v1 attestation; {commit[:12]} predates {CONTEXT_REFERENCE}")


def load_rules(audit, git, commit, ref):
    how = "the report's skill commit"
    if commit is None:
        commit = next(filter(None, (git.resolve(f"refs/{kind}/{ref}") for kind in ("remotes/origin", "heads", "tags"))), None)
        how = f"{ref} tip; the report's skill commit wasn't identified"
        if commit is None:
            raise VerifyError(f"canonical ref {ref!r} not found")
    text = git.out("cat-file", "blob", f"{commit}:monocle/SKILL.md").decode("utf-8")
    audit.rules_source = f"{commit[:12]} ({how})"
    return parse_rules(text)



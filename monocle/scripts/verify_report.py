def synthetic_report(rules, critical=0, high=1, medium=1, low=2, info=1, nonsec=3,
                     each=None, final=None, attestation=True, dirty="false",
                     version="v2", context="none", line_context=None, context_line=True):
    """Build an in-memory report that follows the Output template."""
    charge = dict(rules.each, **(each or {}))
    counts = {"Critical": critical, "High": high, "Medium": medium, "Low": low, "Info": info}
    ids, findings, number = {}, [], 0
    for sev in SEVERITIES:
        ids[sev] = []
        for _ in range(counts[sev]):
            number += 1
            ids[sev].append(f"S{number}")
            findings.append(f"| S{number} | {SEVERITY_EMOJI[sev]} {sev} | Example finding | `tool.sh:{number}` |")
    rows, total = [], 0
    for sev in SEVERITIES:
        total += counts[sev] * charge[sev]
        rows.append(f"| {SEVERITY_EMOJI[sev]} {sev} | {', '.join(ids[sev]) or '—'} | {counts[sev]} | "
                    f"{charge[sev]} | {counts[sev] * charge[sev]} |")
    nonsec_deduction = min(nonsec * rules.nonsec_each, rules.nonsec_cap)
    total += nonsec_deduction
    rows.append(f"| Non-security | example footguns | {nonsec} | {rules.nonsec_each} (max {rules.nonsec_cap}) | {nonsec_deduction} |")
    rows.append("| Not scored | — | 0 | 0 | 0 |")
    raw = 100 - total
    highest = highest_severity(counts)
    final = rules.clamp(raw, highest) if final is None else final
    clamp = (f"; capped at {final} by the {highest} range" if raw > final
             else f"; floored at {final} by the {highest} range" if max(raw, 0) < final else "")
    band = rules.band(final)
    score = f"{final}/100 ({BAND_EMOJI[band]} {band})"
    risk = highest if highest != "none" else "Info"
    commit = "0123456789abcdef0123456789abcdef01234567"
    shown = line_context or context
    context_text = ("Operator-stated (request, 2026-01-01)" if shown == "operator"
                    else "None supplied — documented-deployment baseline")
    context_lines = [f"{CONTEXT_LINE} {context_text}", ""] if context_line else []
    block = [
        "**Attestation:**", "", "~~~text", f"monocle_attestation: {version}",
        f"skill_repo: {CANONICAL_URL}", f"skill_commit: {commit}", "skill_ref: development",
        f"skill_tree: {'1' * 40}", f"skill_sha256: {'2' * 64}", f"skill_dirty: {dirty}",
        "target: tool.sh (attached file)", "target_ref: attached file",
        f"score_raw: {raw}", f"score_final: {final}", "score_alt: none", f"band: {band}",
        *([f"deployment_context: {context}"] if version == "v2" else []),
        "generated_by: Self-test", "timestamp: 2026-01-01 00:00 UTC", "~~~", "",
    ] if attestation else []
    footer_url = f"{CANONICAL_URL}/tree/{commit}" if attestation else CANONICAL_URL
    return "\n".join([
        "# Monocle Report: tool.sh", "## Monocle Score", "", "<details>",
        f"<summary>Monocle Score: {score} — Approve with conditions</summary>", "",
        f"**Score:** {score} at the documented-deployment baseline — synthetic findings", "",
        f"**Overall risk:** {SEVERITY_EMOJI[risk]} {risk}", "",
        "**Recommendation:** Approve with conditions — synthetic reason", "",
        "**Generated by:** Self-test  ·  **Skill:** monocle", "", *context_lines,
        "| Source | IDs | Count | Each | Deduction |", "|---|---|---|---|---|", *rows, "",
        f"**Total:** 100 − {total} = {raw}{clamp} → **{score}**", "",
        "**Operator baseline:** None — the score doesn't depend on deployment.", "",
        "</details>", "", "---", "", "## Contents", "",
        "- [Monocle Score](#monocle-score)", "- [Security View](#security-view)", "- [Scope](#scope)", "",
        "---", "", "## Security View", "", "<details>",
        f"<summary>Security View: {SEVERITY_EMOJI[risk]} {risk} risk</summary>", "",
        "### Findings", "", "| ID | Severity | Title | Location |", "|----|----------|-------|----------|",
        *findings, "", "</details>", "", "---", "", "## Scope", "", "<details>",
        "<summary>Scope: attached file — 1 file, full coverage</summary>", "",
        "| Field | Value |", "|---|---|", "| **Date** | 2026-01-01 00:00 UTC |",
        "| **Target** | tool.sh (attached file) |", "| **Ref** | attached file |",
        "| **Generated by** | Self-test |", "| **Scope caveats** | None |", "",
        *block, "</details>", "", "---", "", f"[Generated by Monocle]({footer_url})", "",
    ])


def stub_provenance(audit):
    """Stand in for the canonical-repository checks, which need the network."""
    att = audit.attestation
    if not att:
        audit.note("provenance", "attestation", "skip", "no attestation")
        return
    audit.add("provenance", "content hash", True, "self-test stub")
    audit.add("provenance", "clean tree", att.get("skill_dirty") == "false", f"skill_dirty: {att.get('skill_dirty')}")


def self_test():
    skill_dir = Path(__file__).resolve().parents[1]
    repo_root = skill_dir.parent
    rules = parse_rules((skill_dir / "SKILL.md").read_text(encoding="utf-8"))
    problems = []

    cases = (
        ("canonical report", {}, OFFICIAL),
        ("missing attestation", {"attestation": False}, SUSPECT),
        ("local edits disclosed", {"dirty": "true"}, WEAKENED),
        ("lowered Critical deduction", {"critical": 1, "high": 0, "each": {"Critical": rules.each["Critical"] // 2}}, WEAKENED),
        ("raised band limit with a clean attestation", {"critical": 1, "high": 0, "final": rules.ranges["Critical"][1] + 10}, FORGED),
        ("no findings", {"high": 0, "medium": 0, "low": 0, "info": 0, "nonsec": 0}, OFFICIAL),
        ("operator-stated context", {"context": "operator"}, OFFICIAL),
        ("legacy v1 attestation", {"version": "v1", "context_line": False}, OFFICIAL),
        ("v2 without a Deployment context line", {"context_line": False}, WEAKENED),
        ("operator context shown as none", {"context": "operator", "line_context": "none"}, WEAKENED),
    )
    for name, options, expected in cases:
        report = Report(synthetic_report(rules, **options))
        audit = run_checks(report)
        stub_provenance(audit)
        check_score(audit, report, rules)
        verdict = decide(audit)
        if verdict != expected:
            failed = "; ".join(f"{c.group}: {c.name} — {c.detail}" for c in audit.checks if c.status == "fail")
            problems.append(f"{name}: expected {expected}, got {verdict} ({failed or 'no failed checks'})")

    # A v1 block attesting a skill commit that already has deployment-context.md is a downgrade.
    class ContextTree:
        def ok(self, *args):
            return True

    report = Report(synthetic_report(rules, version="v1", context_line=False))
    audit = run_checks(report)
    stub_provenance(audit)
    check_context_version(audit, ContextTree(), "0" * 40)
    check_score(audit, report, rules)
    if decide(audit) != WEAKENED:
        problems.append(f"v1 attestation on a context-aware commit: expected {WEAKENED}, got {decide(audit)}")

    with tempfile.TemporaryDirectory() as temp:
        for relative, content in (("SKILL.md", b"a\n"), ("references/x.md", b"b\n"),
                                  (".DS_Store", b"junk"), ("__pycache__/c.pyc", b"junk")):
            Path(temp, relative).parent.mkdir(parents=True, exist_ok=True)
            Path(temp, relative).write_bytes(content)
        expected_text = "".join(f"{hashlib.sha256(c).hexdigest()}  {p}\n"
                                for p, c in (("./SKILL.md", b"a\n"), ("./references/x.md", b"b\n")))
        if manifest_digest(manifest_entries(temp)) != hashlib.sha256(expected_text.encode()).hexdigest():
            problems.append("manifest: digest doesn't match the documented format")

    # CONTRIBUTING.md: scoring guidance stays consistent across SKILL.md, README.md, and security.md.
    each = rules.each
    spans = ", ".join(f"{sev} {'–'.join(map(str, rules.ranges[sev]))}" for sev in ("Critical", "High", "Medium"))
    spans += f", otherwise {'–'.join(map(str, rules.ranges['none']))}"
    expectations = {
        repo_root / "README.md": [
            f"{each['Critical']} / {each['High']} / {each['Medium']} / {each['Low']} |",
            f"{rules.nonsec_each} each, {rules.nonsec_cap} at most", spans,
            ", ".join(f"{low}–{high} {BAND_EMOJI[name]} {name}" for low, high, name in rules.bands),
        ],
        skill_dir / "references" / "security.md": [
            ", ".join(f"{sev} −{each[sev]}" for sev in ("Critical", "High", "Medium", "Low")) + f", Info {each['Info']}",
            f"({spans})",
        ],
    }
    for path, needles in expectations.items():
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        problems += [f"{path.name}: scoring text out of sync with SKILL.md, expected {needle!r}" for needle in needles if needle not in text]

    for problem in problems:
        print(f"FAIL {problem}")
    print(f"self-test: {len(cases)} verdict cases, context-version downgrade, manifest format, scoring-doc sync — "
          f"{'all passed' if not problems else f'{len(problems)} problem(s)'}")
    return 1 if problems else 0



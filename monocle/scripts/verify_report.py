#!/usr/bin/env python3
"""Check whether a Monocle report came from a canonical Monocle skill.

This is the deterministic half of references/verify-report.md. It does four
things:

- parses the report's attestation block and checks it against the canonical
  repository;
- re-derives the Monocle Score from the report's own tables, using the
  scoring rules parsed from canonical SKILL.md;
- checks the report layout;
- flags text that may be trying to steer the checker.

Judgment checks, such as Rule 14 misuse and severity softening, stay with the
agent.

The report is untrusted input. None of its text reaches a shell, and the only
report value ever passed to git is a commit hash that matched a strict
pattern. Fetched repository content is read with git plumbing; it is never
checked out or executed.

Usage:
    verify_report.py REPORT (--fetch | --canonical DIR) [--ref REF] [--json]
    verify_report.py --manifest DIR
    verify_report.py --self-test

Exit status: 0 for OFFICIAL, 1 for any other verdict, 2 for errors.
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import asdict, dataclass, field
from pathlib import Path

CANONICAL_URL = "https://github.com/dan-snelson/Monocle"
CANONICAL_BRANCHES = ("main", "development")
MAX_REPORT_BYTES = 2 * 1024 * 1024
MAX_HISTORY = 500

SEVERITIES = ("Critical", "High", "Medium", "Low", "Info")
BANDS = ("Excellent", "Good", "Fair", "Poor", "Critical")
SEVERITY_EMOJI = {"Critical": "🔴", "High": "🟠", "Medium": "🟡", "Low": "🔵", "Info": "⚪"}
BAND_EMOJI = {"Excellent": "🟢", "Good": "🔵", "Fair": "🟡", "Poor": "🟠", "Critical": "🔴"}
VIEWS = ("Executive View", "Security View", "Manager View", "Engineer View")

OFFICIAL = "OFFICIAL"
SUSPECT = "SUSPECT"
WEAKENED = "NON-CANONICAL / WEAKENED"
FORGED = "FORGED"

ATTESTATION_KEYS = (
    "monocle_attestation", "skill_repo", "skill_commit", "skill_ref", "skill_tree",
    "skill_sha256", "skill_dirty", "target", "target_ref", "score_raw",
    "score_final", "score_alt", "band", "generated_by", "timestamp",
)
# v2 adds deployment_context; v1 blocks come from skill commits before references/deployment-context.md.
ATTESTATION_VERSIONS = ("v1", "v2")
ATTESTATION_KEYS_V2 = ATTESTATION_KEYS + ("deployment_context",)
CONTEXT_REFERENCE = "monocle/references/deployment-context.md"
CONTEXT_LINE = "**Deployment context:**"
CONTEXT_LABELS = {"Operator-stated": "operator", "None supplied": "none"}
COMMIT_RE = re.compile(r"^[0-9a-f]{7,40}$")
TREE_RE = re.compile(r"^[0-9a-f]{40}$")
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
REF_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]*$")
FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})")
FOOTER_RE = re.compile(
    r"^\[Generated by Monocle\]\(https://github\.com/dan-snelson/Monocle(?:/tree/([0-9a-f]{7,40}))?\)$"
)
TOTAL_RE = re.compile(r"^\*\*Total:\*\*\s*100\s*[−-]\s*(.+?)\s*=\s*(-?\d+)(.*)$")
SCORE_RE = re.compile(r"(\d+)/100\s*\(([^)]*)\)")
STEERING_RE = re.compile(
    r"ignore (?:all |any )?(?:previous|prior|above|earlier) instructions"
    r"|\b(?:integrity[- ]checker|verifier|verify_report)\b",
    re.IGNORECASE,
)
MANIFEST_SKIP_FILES = {".DS_Store"}
MANIFEST_SKIP_DIRS = {"__pycache__"}
GIT_ENV = dict(os.environ, GIT_TERMINAL_PROMPT="0", LC_ALL="C")


class VerifyError(Exception):
    """A problem that stops verification: bad input, unparseable rules, or a git failure."""


@dataclass
class Check:
    group: str  # attestation, provenance, rules, arithmetic, structure, steering
    name: str
    status: str  # pass, fail, warn, skip
    detail: str


@dataclass
class Audit:
    checks: list = field(default_factory=list)
    attestation: dict = None
    reported_final: int = None
    reported_band: str = None
    expected_final: int = None
    expected_band: str = None
    rules_source: str = ""
    canonical_source: str = ""

    def add(self, group, name, ok, detail, warn_only=False):
        status = "pass" if ok else ("warn" if warn_only else "fail")
        self.checks.append(Check(group, name, status, detail))

    def note(self, group, name, status, detail):
        self.checks.append(Check(group, name, status, detail))

    def failed(self, *groups):
        return any(check.status == "fail" and check.group in groups for check in self.checks)


@dataclass
class Rules:
    each: dict
    nonsec_each: int
    nonsec_cap: int
    ranges: dict
    bands: list

    def band(self, score):
        for low, high, name in self.bands:
            if low <= score <= high:
                return name
        raise VerifyError(f"no band covers a score of {score}")

    def clamp(self, raw, highest):
        low, high = self.ranges[highest]
        return min(max(max(raw, 0), low), high)

    def score(self, counts, nonsec):
        deductions = sum(self.each[sev] * counts.get(sev, 0) for sev in SEVERITIES)
        deductions += min(nonsec * self.nonsec_each, self.nonsec_cap)
        highest = highest_severity(counts)
        return 100 - deductions, self.clamp(100 - deductions, highest), highest


@dataclass
class Row:
    ids: list
    count: int
    each: int
    cap: int
    deduction: int
    text: str


# ---------------------------------------------------------------- helpers


def word_in(text, words):
    return next((word for word in words if re.search(rf"\b{word}\b", text)), None)


def first_int(text):
    match = re.search(r"-?\d+", text or "")
    return int(match.group()) if match else None


def to_int(text):
    return int(text) if text is not None and re.fullmatch(r"-?\d+", text) else None


def parse_range(text):
    match = re.search(r"(\d+)\s*[–-]\s*(\d+)", text)
    if not match:
        raise VerifyError(f"cannot parse a score range from {text!r}")
    return int(match.group(1)), int(match.group(2))


def highest_severity(counts):
    return next((sev for sev in SEVERITIES if counts.get(sev, 0) > 0), "none")


def cells(line):
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def expand_ids(text):
    ids = []
    for match in re.finditer(r"\bS(\d+)(?:\s*[–-]\s*S?(\d+))?", text):
        low = int(match.group(1))
        high = int(match.group(2) or low)
        if 0 <= high - low <= MAX_HISTORY:
            ids.extend(f"S{n}" for n in range(low, high + 1))
    return ids


def anchor(title):
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


def label(score, band):
    return f"{score}/100 ({band})" if score is not None else "unknown"


def normalize_url(url):
    return re.sub(r"(\.git)?/*$", "", (url or "").strip())


def outside_fences(lines):
    """Yield (index, line) for lines that are not inside a fenced code block."""
    fence = None
    for index, line in enumerate(lines):
        match = FENCE_RE.match(line)
        if fence:
            if re.match(rf"^\s*{re.escape(fence[0])}{{{len(fence)},}}\s*$", line):
                fence = None
        elif match:
            fence = match.group(1)
        else:
            yield index, line


# ---------------------------------------------------------------- manifest


def manifest_entries(root):
    """Return (./relative/path, sha256) for every regular file under a skill directory."""
    root = Path(root)
    if not root.is_dir():
        raise VerifyError(f"{root} is not a directory")
    entries = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [name for name in dirnames if name not in MANIFEST_SKIP_DIRS]
        for name in filenames:
            path = Path(dirpath, name)
            if name in MANIFEST_SKIP_FILES or path.is_symlink() or not path.is_file():
                continue
            relative = "./" + path.relative_to(root).as_posix()
            entries.append((relative, hashlib.sha256(path.read_bytes()).hexdigest()))
    return entries


def manifest_digest(entries):
    """Hash the manifest exactly as the bash stamp in references/attestation.md does."""
    ordered = sorted(entries, key=lambda entry: entry[0].encode("utf-8"))
    text = "".join(f"{digest}  {relative}\n" for relative, digest in ordered)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------- rules


def table_after(lines, marker):
    start = next((i for i, line in enumerate(lines) if line.startswith(marker)), None)
    if start is None:
        raise VerifyError(f"canonical SKILL.md has no {marker} table")
    rows = []
    for line in lines[start + 1:]:
        if line.startswith("|"):
            rows.append(cells(line))
        elif rows:
            break
    return rows[2:]


def parse_rules(text):
    """Parse the Deductions, Band limits, and Bands tables from SKILL.md Step 5."""
    lines = text.splitlines()
    each, nonsec = {}, None
    for row in table_after(lines, "**Deductions.**"):
        numbers = [int(n) for n in re.findall(r"\d+", row[1] if len(row) > 1 else "")]
        if row[0].lower().startswith("non-security") and len(numbers) >= 2:
            nonsec = numbers[:2]
        elif word_in(row[0], SEVERITIES) and numbers:
            each[word_in(row[0], SEVERITIES)] = numbers[0]

    ranges = {}
    for row in table_after(lines, "**Band limits.**"):
        span = parse_range(row[1])
        names = [sev for sev in SEVERITIES if re.search(rf"\b{sev}\b", row[0])]
        if re.search(r"\bnone\b", row[0]):
            names.append("none")
        for name in names:
            ranges[name] = span

    bands = []
    for row in table_after(lines, "**Bands.**"):
        name = word_in(row[1], BANDS) if len(row) > 1 else None
        if name:
            bands.append((*parse_range(row[0]), name))

    missing = [sev for sev in SEVERITIES if sev not in each]
    missing += [] if nonsec else ["Non-security"]
    missing += [f"{sev} range" for sev in ("Critical", "High", "Medium", "Low", "none") if sev not in ranges]
    covered = sorted(n for low, high, _ in bands for n in range(low, high + 1))
    if missing or covered != list(range(101)):
        raise VerifyError(f"could not parse the Step 5 scoring tables (missing: {', '.join(missing) or 'band coverage'})")
    ranges.setdefault("Info", ranges["none"])
    return Rules(each, nonsec[0], nonsec[1], ranges, bands)


# ---------------------------------------------------------------- report


class Report:
    def __init__(self, text):
        self.text = text
        self.lines = text.splitlines()
        heads = [(i, line[3:].strip()) for i, line in outside_fences(self.lines) if line.startswith("## ")]
        self.sections = []
        for n, (start, title) in enumerate(heads):
            end = heads[n + 1][0] if n + 1 < len(heads) else len(self.lines)
            self.sections.append((title, start, end))
        self.by_title = {}
        for title, start, end in self.sections:
            self.by_title.setdefault(title, (start, end))
        nonblank = [line.strip() for line in self.lines if line.strip()]
        self.footer = nonblank[-1] if nonblank else ""
        self.before_footer = nonblank[-2] if len(nonblank) > 1 else ""
        match = FOOTER_RE.match(self.footer)
        self.footer_ok = bool(match)
        self.footer_commit = match.group(1) if match else None

    def body(self, title):
        start, end = self.by_title.get(title, (0, 0))
        return self.lines[start:end]

    def table(self, title, header):
        lines = self.body(title)
        for i, line in enumerate(lines):
            if line.startswith("|") and [c.lower() for c in cells(line)][: len(header)] == list(header):
                rows = []
                for row in lines[i + 2:]:
                    if not row.startswith("|"):
                        break
                    rows.append(cells(row))
                return rows
        return None

    def scope_fields(self):
        rows = self.table("Scope", ("field", "value")) or []
        return {row[0].strip("* "): row[1] for row in rows if len(row) >= 2}


def parse_attestation(lines):
    starts = [i for i, line in enumerate(lines) if re.match(r"^\s*monocle_attestation\s*:", line)]
    if not starts:
        return None, starts, []
    values, duplicates = {}, []
    for line in lines[starts[0]:]:
        match = re.match(r"^\s*([a-z0-9_]+)\s*:\s*(.*?)\s*$", line)
        if not match:
            break
        if match.group(1) in values:
            duplicates.append(match.group(1))
        values.setdefault(match.group(1), match.group(2))
    return values, starts, duplicates


# ---------------------------------------------------------------- checks


def check_structure(audit, report):
    lines, titles = report.lines, [title for title, _, _ in report.sections]
    audit.add("structure", "title", bool(lines) and lines[0].startswith("# Monocle Report:"),
              f"line 1 is {lines[0][:60]!r}" if lines else "report is empty")
    audit.add("structure", "Monocle Score on line 2", len(lines) > 1 and lines[1] == "## Monocle Score",
              "`## Monocle Score` must follow the title directly")
    views = [title for title in titles if title in VIEWS]
    audit.add("structure", "views present", bool(views),
              f"views found: {', '.join(views) or 'none'}")
    audit.add("structure", "view order", views == [v for v in VIEWS if v in views],
              f"order found: {', '.join(views)}", warn_only=True)
    audit.add("structure", "Scope section", "Scope" in titles, "a `## Scope` section is required")
    audit.add("structure", "Scope last", titles[-1:] == ["Scope"],
              f"last section is {titles[-1] if titles else 'missing'}", warn_only=True)

    links = re.findall(r"^- \[([^\]]+)\]\(#([^)]+)\)", "\n".join(report.body("Contents")), re.MULTILINE)
    expected = [title for title in titles if title != "Contents"]
    audit.add("structure", "Contents", [t for t, _ in links] == expected and all(a == anchor(t) for t, a in links),
              f"Contents links {[t for t, _ in links]}; sections {expected}", warn_only=True)
    collapsed = []
    for title, start, end in report.sections:
        following = next((line.strip() for line in report.lines[start + 1:end] if line.strip()), "")
        if title != "Contents" and following != "<details>":
            collapsed.append(title)
    audit.add("structure", "collapsed sections", not collapsed,
              f"sections not wrapped in a plain <details>: {', '.join(collapsed) or 'none'}", warn_only=True)

    audit.add("structure", "footer", report.footer_ok,
              f"last line must be the Monocle footer; found {report.footer[:100]!r}")
    audit.add("structure", "footer rule", report.before_footer == "---",
              "a `---` line must precede the footer", warn_only=True)


def check_attestation(audit, report):
    values, starts, duplicates = parse_attestation(report.lines)
    if values is None:
        audit.add("attestation", "present", False, "no `monocle_attestation:` block; the report can't be considered official")
        return
    audit.attestation = values
    version = values.get("monocle_attestation")
    keys = ATTESTATION_KEYS_V2 if version == "v2" else ATTESTATION_KEYS
    missing = [key for key in keys if key not in values]
    audit.add("attestation", "complete", not missing, f"missing fields: {', '.join(missing) or 'none'}")
    audit.add("attestation", "single block", len(starts) == 1 and not duplicates,
              f"{len(starts)} attestation block(s); repeated fields: {', '.join(duplicates) or 'none'}")
    audit.add("attestation", "version", version in ATTESTATION_VERSIONS,
              f"monocle_attestation: {version!r} (expected {' or '.join(ATTESTATION_VERSIONS)})")

    formats = {
        "skill_commit": lambda v: v == "unknown" or COMMIT_RE.match(v),
        "skill_tree": lambda v: v == "unavailable" or TREE_RE.match(v),
        "skill_sha256": lambda v: SHA256_RE.match(v),
        "skill_dirty": lambda v: v in ("true", "false", "unknown"),
        "score_raw": lambda v: to_int(v) is not None,
        "score_final": lambda v: to_int(v) is not None and 0 <= to_int(v) <= 100,
        "score_alt": lambda v: v == "none" or (to_int(v) is not None and 0 <= to_int(v) <= 100),
        "deployment_context": lambda v: v in CONTEXT_LABELS.values(),
    }
    bad = [f"{key}={values[key]!r}" for key, test in formats.items() if key in values and not test(values[key])]
    audit.add("attestation", "field formats", not bad, f"malformed: {', '.join(bad) or 'none'}")

    start, end = report.by_title.get("Scope", (0, 0))
    audit.add("attestation", "inside Scope", start <= starts[0] < end,
              "the attestation block belongs at the end of the Scope section", warn_only=True)

    audit.add("provenance", "skill repository", normalize_url(values.get("skill_repo")) == CANONICAL_URL,
              f"skill_repo: {values.get('skill_repo')!r}; canonical is {CANONICAL_URL}")
    commit = values.get("skill_commit", "")
    if report.footer_commit:
        audit.add("provenance", "footer commit", COMMIT_RE.match(commit) is not None
                  and (commit.startswith(report.footer_commit) or report.footer_commit.startswith(commit)),
                  f"footer pins {report.footer_commit}; attestation claims {commit}")
    elif COMMIT_RE.match(commit):
        audit.note("structure", "footer commit", "warn", "footer link isn't pinned to the attested commit")

    scope = report.scope_fields()
    for key, field_name in (("target", "Target"), ("target_ref", "Ref"), ("generated_by", "Generated by"), ("timestamp", "Date")):
        if field_name in scope and key in values:
            audit.add("attestation", f"{key} matches Scope", values[key] == scope[field_name],
                      f"attestation {values[key]!r}; Scope {field_name} {scope[field_name]!r}", warn_only=True)


def check_context_line(audit, body, attested):
    """A v2 report shows its Deployment Context, and the line agrees with the attestation."""
    line = next((line for line in body if line.startswith(CONTEXT_LINE)), None)
    audit.add("structure", "Deployment context line", line is not None,
              f"`{CONTEXT_LINE}` line {'present' if line else 'missing'} in the Monocle Score section")
    if line is None:
        return
    text = line[len(CONTEXT_LINE):].strip()
    shown = next((value for label_text, value in CONTEXT_LABELS.items() if text.startswith(label_text)), None)
    audit.add("structure", "Deployment context matches attestation", shown == attested,
              f"line reads {text[:60]!r}; attestation deployment_context is {attested!r}")


def check_steering(audit, report):
    # Fenced blocks count too: a quoted "snippet" is an easy place to hide an instruction.
    hits = [line.strip()[:120] for line in report.lines if STEERING_RE.search(line)]
    detail = ("possible text aimed at the checker; judge it per verify-report.md: " + " | ".join(hits[:3])
              if hits else "no text addressed to a verifier")
    audit.add("steering", "checker-steering text", not hits, detail, warn_only=True)


def check_score(audit, report, rules):
    if "Monocle Score" not in report.by_title:
        audit.add("structure", "Monocle Score section", False, "no `## Monocle Score` section")
        return
    body = report.body("Monocle Score")
    for prefix in ("**Score:**", "**Overall risk:**", "**Recommendation:**", "**Generated by:**", "**Operator baseline:**"):
        present = any(line.startswith(prefix) for line in body)
        audit.add("structure", f"{prefix.strip('*:')} line", present,
                  f"`{prefix}` line {'present' if present else 'missing'} in the Monocle Score section")
    att = audit.attestation or {}
    if att.get("monocle_attestation") == "v2":
        check_context_line(audit, body, att.get("deployment_context"))

    table = report.table("Monocle Score", ("source", "ids", "count", "each", "deduction"))
    if table is None:
        audit.add("structure", "deduction table", False, "no `| Source | IDs | Count | Each | Deduction |` table")
        return

    rows = {}
    for row in table:
        if len(row) < 5:
            continue
        lower = row[0].lower()
        key = ("Non-security" if lower.startswith("non-security")
               else "Not scored" if lower.startswith("not scored") else word_in(row[0], SEVERITIES))
        if key:
            cap = re.search(r"max\D*(\d+)", row[3])
            rows[key] = Row(expand_ids(row[1]), first_int(row[2]) or 0, first_int(row[3]),
                            int(cap.group(1)) if cap else None, first_int(row[4]), "| " + " | ".join(row) + " |")

    # Rule fidelity: per-finding deductions and the non-security cap.
    for sev in SEVERITIES:
        row = rows.get(sev)
        if row is None:
            audit.add("rules", f"{sev} row", False, f"the deduction table has no {sev} row")
            continue
        audit.add("rules", f"{sev} deduction", row.each == rules.each[sev],
                  f"report charges {row.each} per {sev} finding; canonical SKILL.md charges {rules.each[sev]} (`{row.text}`)")
    nonsec_row = rows.get("Non-security")
    if nonsec_row is None:
        audit.add("rules", "Non-security row", False, "the deduction table has no Non-security row")
    else:
        audit.add("rules", "Non-security deduction",
                  (nonsec_row.each, nonsec_row.cap) == (rules.nonsec_each, rules.nonsec_cap),
                  f"report: {nonsec_row.each} each, max {nonsec_row.cap}; canonical: {rules.nonsec_each} each, "
                  f"max {rules.nonsec_cap} (`{nonsec_row.text}`)")

    # Arithmetic within the table.
    for key, row in rows.items():
        each = row.each or 0
        if key == "Non-security":
            expected = min(row.count * each, row.cap if row.cap is not None else rules.nonsec_cap)
        elif key == "Not scored":
            expected = 0
        else:
            expected = row.count * each
            if row.ids:
                audit.add("arithmetic", f"{key} IDs", len(row.ids) == row.count,
                          f"{len(row.ids)} IDs listed ({', '.join(row.ids)}) but Count is {row.count}")
        audit.add("arithmetic", f"{key} row", row.deduction == expected,
                  f"Deduction {row.deduction}; Count × Each gives {expected} (`{row.text}`)")

    counts = {sev: rows[sev].count if sev in rows else 0 for sev in SEVERITIES}
    nonsec = nonsec_row.count if nonsec_row else 0

    # Cross-check against the Security view findings table.
    findings = report.table("Security View", ("id", "severity"))
    table_counts, table_sev = {sev: 0 for sev in SEVERITIES}, {}
    if findings is None:
        audit.note("arithmetic", "findings table", "skip", "no Security view findings table (subset report?)")
    else:
        for row in findings:
            sev = word_in(row[1], SEVERITIES) if len(row) > 1 else None
            if sev:
                table_counts[sev] += 1
                table_sev[row[0].strip()] = sev
        for sev in SEVERITIES:
            scored, listed = counts[sev], table_counts[sev]
            if sev == "Low" and scored == listed + 1:
                audit.note("arithmetic", "Low count", "warn",
                           f"one more Low scored ({scored}) than listed ({listed}); valid only for a roll-up that names a real gap")
            else:
                audit.add("arithmetic", f"{sev} count", scored == listed,
                          f"findings table lists {listed} {sev}; deduction table counts {scored}", warn_only=sev == "Info")
            for finding_id in rows[sev].ids if sev in rows else []:
                if finding_id in table_sev and table_sev[finding_id] != sev:
                    audit.add("arithmetic", f"{finding_id} severity", False,
                              f"{finding_id} is {table_sev[finding_id]} in the findings table but scored as {sev}")

    # The Total line: deductions, raw score, clamp, and band.
    total_line = next((line for line in body if line.startswith("**Total:**")), None)
    match = TOTAL_RE.match(total_line or "")
    if not match:
        audit.add("structure", "Total line", False, f"missing or unparseable Total line: {total_line!r}")
        return
    stated_sum = sum(int(n) for n in re.findall(r"\d+", match.group(1)))
    table_sum = sum(row.deduction or 0 for row in rows.values())
    audit.add("arithmetic", "Total deductions", stated_sum == table_sum,
              f"Total subtracts {stated_sum}; the table's Deduction column sums to {table_sum}")
    raw = int(match.group(2))
    audit.add("arithmetic", "raw score", raw in (100 - stated_sum, max(0, 100 - stated_sum)),
              f"100 − {stated_sum} should be {100 - stated_sum}; Total says {raw}")
    final_match = re.search(r"\*\*(\d+)/100\s*\(([^)]*)\)\*\*", match.group(3))
    if not final_match:
        audit.add("structure", "Total result", False, f"Total line has no **n/100 (band)** result: {total_line!r}")
        return
    final, band = int(final_match.group(1)), word_in(final_match.group(2), BANDS)
    audit.reported_final, audit.reported_band = final, band

    highest = highest_severity(counts)
    clamped = rules.clamp(raw, highest)
    low, high = rules.ranges[highest]
    audit.add("rules", "band limit", final == clamped,
              f"highest scored severity is {highest} (range {low}–{high}); raw {raw} clamps to {clamped}, report gives {final}")
    phrase = re.search(r"\b(capped|floored) at (\d+)", match.group(3))
    wanted = "capped" if raw > high else "floored" if max(raw, 0) < low else None
    audit.add("rules", "clamp wording", (phrase.group(1) if phrase else None) == wanted,
              f"Total says {phrase.group(0) if phrase else 'no clamp'}; canonical rules give {wanted or 'no clamp'}", warn_only=True)
    audit.add("arithmetic", "band", band == rules.band(final),
              f"{final} is {rules.band(final)} under canonical bands; report says {band}")

    # Every place the headline appears must agree.
    summary = next((SCORE_RE.search(line) for line in body if line.startswith("<summary>Monocle Score:")), None)
    score_line = next((line for line in body if line.startswith("**Score:**")), "")
    score_match = SCORE_RE.search(score_line)
    alt_match = re.search(r",\s*or\s+(\d+)/100\s*\(([^)]*)\)", score_line)
    shown = {"summary": summary, "Score line": score_match}
    for where, found in shown.items():
        audit.add("arithmetic", f"{where} score", bool(found) and int(found.group(1)) == final,
                  f"{where} shows {found.group(0) if found else 'no score'}; Total gives {final}/100")
    if att:
        audit.add("arithmetic", "attested final", to_int(att.get("score_final")) == final,
                  f"attestation score_final {att.get('score_final')}; Total gives {final}")
        audit.add("arithmetic", "attested raw", to_int(att.get("score_raw")) in (raw, max(raw, 0)),
                  f"attestation score_raw {att.get('score_raw')}; Total gives {raw}")
        audit.add("arithmetic", "attested band", att.get("band") == band,
                  f"attestation band {att.get('band')!r}; Total gives {band!r}")
        alt = alt_match.group(1) if alt_match else "none"
        audit.add("arithmetic", "attested alternate", att.get("score_alt") == alt,
                  f"attestation score_alt {att.get('score_alt')!r}; Score line alternate {alt!r}")
    if alt_match:
        alt, alt_band = int(alt_match.group(1)), word_in(alt_match.group(2), BANDS)
        audit.add("arithmetic", "alternate band", alt_band == rules.band(alt),
                  f"alternate {alt} is {rules.band(alt)} under canonical bands; report says {alt_band}")
        audit.add("arithmetic", "alternate direction", alt <= final,
                  f"alternate {alt} is above the headline {final}; a misconfigured case shouldn't score higher", warn_only=True)
    elif att.get("deployment_context") == "operator":
        audit.note("structure", "context alternate", "warn",
                   "operator-stated context but no alternate score; valid only if the context changed no rating")

    # What canonical rules give for the findings this report lists. Taking the larger
    # count per severity means findings dropped from the table are still charged.
    expected_counts = {sev: max(counts[sev], table_counts[sev]) for sev in SEVERITIES}
    _, audit.expected_final, _ = rules.score(expected_counts, nonsec)
    audit.expected_band = rules.band(audit.expected_final)
    audit.add("arithmetic", "official score", final == audit.expected_final,
              f"canonical rules give {label(audit.expected_final, audit.expected_band)} for these findings; "
              f"report gives {label(final, band)}")



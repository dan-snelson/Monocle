    source.add_argument("--canonical", metavar="DIR", help="use an existing clone of the canonical repository")
    parser.add_argument("--ref", default="development",
                        help="canonical branch or tag whose rules apply when the report's skill commit isn't identified")
    parser.add_argument("--json", action="store_true", help="print machine-readable results")
    parser.add_argument("--manifest", metavar="DIR", help="print the skill_sha256 of a skill directory and exit")
    parser.add_argument("--self-test", action="store_true", help="run the built-in checks and exit")
    args = parser.parse_args(argv)
    try:
        if args.self_test:
            return self_test()
        if args.manifest:
            print(manifest_digest(manifest_entries(args.manifest)))
            return 0
        if not args.report or not (args.fetch or args.canonical):
            parser.error("give a REPORT and either --fetch or --canonical DIR")
        if not REF_RE.match(args.ref):
            parser.error("--ref must be a branch or tag name")
        return verify(args)
    except (VerifyError, OSError) as error:
        print(f"verify_report.py: {error}", file=sys.stderr)
        return 2



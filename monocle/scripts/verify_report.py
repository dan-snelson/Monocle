def decide(audit):
    att = audit.attestation
    if att and not audit.failed("attestation"):
        attested = to_int(att.get("score_final"))
        if audit.reported_final is not None and attested is not None and audit.reported_final > attested:
            return FORGED
        favorable = (audit.reported_final is not None and audit.expected_final is not None
                     and audit.reported_final > audit.expected_final)
        if att.get("skill_dirty") == "false" and favorable and audit.failed("rules", "arithmetic"):
            return FORGED
    if audit.failed("provenance", "rules", "arithmetic", "structure"):
        return WEAKENED
    if audit.failed("attestation"):
        return SUSPECT
    return OFFICIAL


def run_checks(report):
    audit = Audit()
    check_structure(audit, report)
    check_attestation(audit, report)
    check_steering(audit, report)
    return audit


def render(audit, verdict, path):
    order = {"fail": 0, "warn": 1, "skip": 2, "pass": 3}
    lines = [
        f"Report: {path}",
        f"Canonical source: {audit.canonical_source}",
        f"Scoring rules from: {audit.rules_source}",
        f"Mechanical verdict: {verdict}",
        f"Reported score: {label(audit.reported_final, audit.reported_band)}; "
        f"canonical rules give: {label(audit.expected_final, audit.expected_band)}",
        "",
    ]
    for check in sorted(audit.checks, key=lambda c: order[c.status]):
        lines.append(f"[{check.status.upper()}] {check.group}: {check.name} — {check.detail}")
    return "\n".join(lines)


def read_report(path):
    if path == "-":
        data = sys.stdin.buffer.read(MAX_REPORT_BYTES + 1)
    else:
        with open(path, "rb") as handle:
            data = handle.read(MAX_REPORT_BYTES + 1)
    if len(data) > MAX_REPORT_BYTES:
        raise VerifyError(f"report is over {MAX_REPORT_BYTES} bytes")
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise VerifyError(f"report isn't UTF-8 text: {error}") from error


def verify(args):
    report = Report(read_report(args.report))
    audit = run_checks(report)
    git, source, temp, trusted = open_canonical(args)
    audit.canonical_source = source
    try:
        if not trusted:
            audit.note("provenance", "canonical source", "warn",
                       f"the --canonical clone's origin isn't {CANONICAL_URL}; results are only as good as that clone")
        refs = git.refs()
        if not refs:
            raise VerifyError("canonical repository has no main, development, or tag refs")
        commit = check_provenance(audit, git, refs)
        rules = load_rules(audit, git, commit, args.ref)
        check_score(audit, report, rules)
    finally:
        if temp:
            shutil.rmtree(temp, ignore_errors=True)
    verdict = decide(audit)
    if args.json:
        print(json.dumps({
            "report": args.report,
            "verdict": verdict,
            "canonical_source": audit.canonical_source,
            "canonical_source_trusted": trusted and bool(args.fetch),
            "rules_source": audit.rules_source,
            "reported_score": audit.reported_final,
            "reported_band": audit.reported_band,
            "expected_score": audit.expected_final,
            "expected_band": audit.expected_band,
            "attestation": audit.attestation,
            "checks": [asdict(check) for check in audit.checks],
        }, indent=2, ensure_ascii=False))
    else:
        print(render(audit, verdict, args.report))
    return 0 if verdict == OFFICIAL else 1


